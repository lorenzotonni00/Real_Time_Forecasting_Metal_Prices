function missing_lags = ragged_edge_missing_lags(ids)

missing_lags = zeros(1,numel(ids));

two_month_lag_ids = { ...
    'INDPRO', ...
    'CPIAUCSL', ...
    'A31SNO', ...
    'AANMNO', ...
    'ANMNO', ...
    'AWHMAN', ...
    'CAPUTLB562A3CS', ...
    'CAPUTLG331S', ...
    'PCU331331', ...
    'PCU335911335911', ...
    'RBAUBIS', ...
    'RBCLBIS', ...
    'RBCNBIS', ...
    'RBIDBIS', ...
    'RBPEBIS', ...
    'RBPHBIS', ...
    'RBRUBIS'};

for ii = 1:numel(ids)
    if strcmp(ids{ii}, 'A35DVS')
        missing_lags(ii) = 3;
    elseif any(strcmp(ids{ii}, two_month_lag_ids))
        missing_lags(ii) = 2;
    end
end

end
